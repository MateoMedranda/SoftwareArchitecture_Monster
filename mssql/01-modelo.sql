/* 1. Base de datos */
IF DB_ID('arquitectura_db') IS NULL
BEGIN
    CREATE DATABASE arquitectura_db;
END
GO

USE arquitectura_db;
GO

/* 2. Logins y usuarios */
IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = 'MONSTER')
BEGIN
    CREATE LOGIN MONSTER WITH PASSWORD = 'MONSTER9', CHECK_POLICY = OFF, CHECK_EXPIRATION = OFF;
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = 'admin')
BEGIN
    CREATE LOGIN admin WITH PASSWORD = 'admin', CHECK_POLICY = OFF, CHECK_EXPIRATION = OFF;
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = 'MONSTER')
BEGIN
    CREATE USER MONSTER FOR LOGIN MONSTER;
    ALTER ROLE db_owner ADD MEMBER MONSTER;
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = 'admin')
BEGIN
    CREATE USER admin FOR LOGIN admin;
    ALTER ROLE db_owner ADD MEMBER admin;
END
GO

/* 3. Esquema (MER EUREKABANK) */
IF OBJECT_ID('dbo.PERTENECE', 'U') IS NOT NULL DROP TABLE dbo.PERTENECE;
IF OBJECT_ID('dbo.TRANSACCION', 'U') IS NOT NULL DROP TABLE dbo.TRANSACCION;
IF OBJECT_ID('dbo.TOKEN', 'U') IS NOT NULL DROP TABLE dbo.TOKEN;
IF OBJECT_ID('dbo.CUENTA', 'U') IS NOT NULL DROP TABLE dbo.CUENTA;
IF OBJECT_ID('dbo.USUARIO', 'U') IS NOT NULL DROP TABLE dbo.USUARIO;
IF OBJECT_ID('dbo.SUCURSAL', 'U') IS NOT NULL DROP TABLE dbo.SUCURSAL;
IF OBJECT_ID('dbo.ROL', 'U') IS NOT NULL DROP TABLE dbo.ROL;
GO

CREATE TABLE dbo.ROL
(
   ROL_ID               VARCHAR(36) NOT NULL,
   ROL_NOMBRE           VARCHAR(36) NOT NULL,
   CONSTRAINT PK_ROL PRIMARY KEY (ROL_ID),
   CONSTRAINT UK_ROL_NOMBRE UNIQUE (ROL_NOMBRE)
);

CREATE TABLE dbo.SUCURSAL
(
   SUCURSAL_ID          VARCHAR(36) NOT NULL,
   SUCURSAL_NOMBRE      VARCHAR(64) NOT NULL,
   CONSTRAINT PK_SUCURSAL PRIMARY KEY (SUCURSAL_ID)
);

CREATE TABLE dbo.USUARIO
(
   USUARIO_NOMBRE       VARCHAR(36) NOT NULL,
   USUARIO_ID           VARCHAR(36) NOT NULL,
   ROL_ID               VARCHAR(36) NULL,
   USUARIO_APELLIDO     VARCHAR(36) NOT NULL,
   USUARIO_TELEFONO     VARCHAR(36) NOT NULL,
   USUARIO_USUARIO      VARCHAR(36) NOT NULL,
   USUARIO_CONTRASEANIA VARCHAR(64) NOT NULL,
   CONSTRAINT PK_USUARIO PRIMARY KEY (USUARIO_ID),
   CONSTRAINT UK_USUARIO_USUARIO UNIQUE (USUARIO_USUARIO),
   CONSTRAINT FK_PUEDE_SER FOREIGN KEY (ROL_ID) REFERENCES dbo.ROL(ROL_ID)
);

CREATE TABLE dbo.CUENTA
(
   CUENTA_SALDO         DECIMAL(15,2) NOT NULL,
   CUENTA_ESTADO        VARCHAR(24) NOT NULL,
   CUENTA_ID            VARCHAR(36) NOT NULL,
   SUCURSAL_ID          VARCHAR(36) NULL,
   CONSTRAINT PK_CUENTA PRIMARY KEY (CUENTA_ID),
   CONSTRAINT FK_TIENE FOREIGN KEY (SUCURSAL_ID) REFERENCES dbo.SUCURSAL(SUCURSAL_ID)
);

CREATE TABLE dbo.PERTENECE
(
   CUENTA_ID            VARCHAR(36) NOT NULL,
   USUARIO_ID           VARCHAR(36) NOT NULL,
   CONSTRAINT PK_PERTENECE PRIMARY KEY (CUENTA_ID, USUARIO_ID),
   CONSTRAINT FK_PERTENECE FOREIGN KEY (CUENTA_ID) REFERENCES dbo.CUENTA(CUENTA_ID),
   CONSTRAINT FK_PERTENECE2 FOREIGN KEY (USUARIO_ID) REFERENCES dbo.USUARIO(USUARIO_ID)
);

CREATE TABLE dbo.TOKEN
(
   TOKEN_TOKEN          VARCHAR(124) NOT NULL,
   TOKEN_ESTADO         VARCHAR(24) NOT NULL,
   TOKEN_ID             VARCHAR(36) NOT NULL,
   USUARIO_ID           VARCHAR(36) NOT NULL,
   TOKEN_CREADO_EN      DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
   CONSTRAINT PK_TOKEN PRIMARY KEY (TOKEN_ID),
   CONSTRAINT FK_TIENE_ASIGNADO FOREIGN KEY (USUARIO_ID) REFERENCES dbo.USUARIO(USUARIO_ID)
);

CREATE TABLE dbo.TRANSACCION
(
   TRANSACCION_ID       VARCHAR(36) NOT NULL,
   CUENTA_ID            VARCHAR(36) NOT NULL,
   TRANSACCION_SALDO    DECIMAL(10,2) NOT NULL,
   TRANSACCION_TIPO     VARCHAR(36) NOT NULL,
   TRANSACCION_SALDO_ANTERIOR DECIMAL(12,2) NOT NULL,
   TRANSACCION_SALDO_POSTERIOR DECIMAL(12,2) NOT NULL,
   TRANSACCION_CREADO_EN DATETIME2 NOT NULL,
   TRANSACCION_CREADO_POR VARCHAR(36) NOT NULL,
   CONSTRAINT PK_TRANSACCION PRIMARY KEY (TRANSACCION_ID),
   CONSTRAINT FK_GENERA FOREIGN KEY (CUENTA_ID) REFERENCES dbo.CUENTA(CUENTA_ID)
);
GO

ALTER TABLE dbo.CUENTA ADD CUENTA_NUMERO VARCHAR(10) NULL;
GO
