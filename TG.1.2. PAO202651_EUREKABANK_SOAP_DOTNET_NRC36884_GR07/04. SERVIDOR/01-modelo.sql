USE master;
GO
IF DB_ID(N'arquitectura_db') IS NULL CREATE DATABASE arquitectura_db;
GO
USE arquitectura_db;
GO
DROP TABLE IF EXISTS dbo.PERTENECE;
DROP TABLE IF EXISTS dbo.TRANSACCION;
DROP TABLE IF EXISTS dbo.TOKEN;
DROP TABLE IF EXISTS dbo.CUENTA;
DROP TABLE IF EXISTS dbo.USUARIO;
DROP TABLE IF EXISTS dbo.SUCURSAL;
DROP TABLE IF EXISTS dbo.ROL;
GO
CREATE TABLE dbo.ROL (ROL_ID varchar(36) NOT NULL CONSTRAINT PK_ROL PRIMARY KEY, ROL_NOMBRE varchar(36) NOT NULL CONSTRAINT UQ_ROL_NOMBRE UNIQUE);
CREATE TABLE dbo.SUCURSAL (SUCURSAL_ID varchar(36) NOT NULL CONSTRAINT PK_SUCURSAL PRIMARY KEY, SUCURSAL_NOMBRE varchar(64) NOT NULL);
CREATE TABLE dbo.USUARIO (
 USUARIO_ID varchar(36) NOT NULL CONSTRAINT PK_USUARIO PRIMARY KEY, ROL_ID varchar(36) NULL, USUARIO_NOMBRE varchar(36) NOT NULL, USUARIO_APELLIDO varchar(36) NOT NULL,
 USUARIO_TELEFONO varchar(36) NOT NULL, USUARIO_USUARIO varchar(36) NOT NULL CONSTRAINT UQ_USUARIO_USUARIO UNIQUE, USUARIO_CONTRASEANIA varchar(64) NOT NULL,
 CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ROL_ID) REFERENCES dbo.ROL(ROL_ID));
CREATE TABLE dbo.CUENTA (
 CUENTA_ID varchar(36) NOT NULL CONSTRAINT PK_CUENTA PRIMARY KEY, SUCURSAL_ID varchar(36) NULL, CUENTA_NUMERO varchar(10) NOT NULL CONSTRAINT UQ_CUENTA_NUMERO UNIQUE,
 CUENTA_SALDO decimal(15,2) NOT NULL CONSTRAINT DF_CUENTA_SALDO DEFAULT 0, CUENTA_ESTADO varchar(24) NOT NULL,
 CONSTRAINT FK_CUENTA_SUCURSAL FOREIGN KEY (SUCURSAL_ID) REFERENCES dbo.SUCURSAL(SUCURSAL_ID));
CREATE TABLE dbo.PERTENECE (CUENTA_ID varchar(36) NOT NULL, USUARIO_ID varchar(36) NOT NULL, CONSTRAINT PK_PERTENECE PRIMARY KEY (CUENTA_ID,USUARIO_ID), CONSTRAINT FK_PERTENECE_CUENTA FOREIGN KEY (CUENTA_ID) REFERENCES dbo.CUENTA(CUENTA_ID), CONSTRAINT FK_PERTENECE_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES dbo.USUARIO(USUARIO_ID));
CREATE TABLE dbo.TOKEN (TOKEN_ID varchar(36) NOT NULL CONSTRAINT PK_TOKEN PRIMARY KEY, TOKEN_TOKEN varchar(124) NOT NULL CONSTRAINT UQ_TOKEN_TOKEN UNIQUE, TOKEN_ESTADO varchar(24) NOT NULL, USUARIO_ID varchar(36) NOT NULL, TOKEN_CREADO_EN datetime2 NOT NULL CONSTRAINT DF_TOKEN_CREADO_EN DEFAULT SYSUTCDATETIME(), CONSTRAINT FK_TOKEN_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES dbo.USUARIO(USUARIO_ID));
CREATE TABLE dbo.TRANSACCION (
 TRANSACCION_ID varchar(36) NOT NULL CONSTRAINT PK_TRANSACCION PRIMARY KEY, CUENTA_ID varchar(36) NOT NULL, TRANSACCION_SALDO decimal(15,2) NOT NULL, TRANSACCION_TIPO varchar(36) NOT NULL,
 TRANSACCION_SALDO_ANTERIOR decimal(15,2) NOT NULL, TRANSACCION_SALDO_POSTERIOR decimal(15,2) NOT NULL, TRANSACCION_CREADO_EN datetime2 NOT NULL, TRANSACCION_CREADO_POR varchar(36) NOT NULL,
 CONSTRAINT FK_TRANSACCION_CUENTA FOREIGN KEY (CUENTA_ID) REFERENCES dbo.CUENTA(CUENTA_ID));
GO
